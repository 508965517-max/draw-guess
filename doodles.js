// 机器人"反画"用的简笔画库。
// 每个词条返回一组折线（polyline），每条折线是 [{x,y}, ...]，坐标范围约 0~1（会被前端缩放铺满画布）。
// 笔画由房主（模拟机器人作画）按段下发，营造"机器人正在画"的渐进效果。

function circle(cx, cy, r, steps = 28, a0 = 0, a1 = Math.PI * 2) {
  const p = [];
  for (let i = 0; i <= steps; i++) {
    const a = a0 + (a1 - a0) * (i / steps);
    p.push({ x: cx + r * Math.cos(a), y: cy + r * Math.sin(a) });
  }
  return p;
}
function ellipse(cx, cy, rx, ry, steps = 28, a0 = 0, a1 = Math.PI * 2) {
  const p = [];
  for (let i = 0; i <= steps; i++) {
    const a = a0 + (a1 - a0) * (i / steps);
    p.push({ x: cx + rx * Math.cos(a), y: cy + ry * Math.sin(a) });
  }
  return p;
}
function L(x1, y1, x2, y2) { return [{ x: x1, y: y1 }, { x: x2, y: y2 }]; }
function P(...pts) { return pts.map((p) => ({ x: p[0], y: p[1] })); }
function star(cx, cy, R, points = 5) {
  const r = R * 0.42, p = [];
  for (let i = 0; i < points * 2; i++) {
    const rad = i % 2 ? r : R;
    const a = -Math.PI / 2 + (i * Math.PI) / points;
    p.push({ x: cx + rad * Math.cos(a), y: cy + rad * Math.sin(a) });
  }
  p.push(p[0]);
  return p;
}
function heart(cx, cy, s) {
  const p = [], steps = 30;
  for (let i = 0; i <= steps; i++) {
    const t = Math.PI - (Math.PI * 2) * (i / steps);
    const x = 16 * Math.pow(Math.sin(t), 3);
    const y = 13 * Math.cos(t) - 5 * Math.cos(2 * t) - 2 * Math.cos(3 * t) - Math.cos(4 * t);
    p.push({ x: cx + (x * s) / 16, y: cy - (y * s) / 16 });
  }
  return p;
}

